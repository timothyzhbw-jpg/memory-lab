"""Audit a directory's memory and instruction files together: ``memfalsify audit`` with no MEMORY argument.

The files are what ``discover`` lists plus a top-level ``MEMORY.md``. The evidence is scanned once and follows the
web page's rules: ``scan``'s skips, Memory Lab's own files left out, and each file's evidence
holding everything but that file and the files it links to. So agent files count as evidence for each other,
which is how two files that disagree show up.

Claims and reviews are shared across the files. A claim stated in several files is reported once, under the first
file (in path order) that states it, and lists the others in its ``duplicate`` issue; a linked file's claims are
reported under that file if it is one of the chosen files, otherwise under the first file linking to it.
"""
from __future__ import annotations

import os
from collections import Counter
from collections.abc import Callable, Iterable
from datetime import date
from pathlib import Path, PurePosixPath

from memcore import EvidenceError
from memcore.paths import InputPathError, input_path

from .audit import NOTHING_LEFT, SEVERITY, AuditReport, AuditSet, _ConflictIndex, add_missing_references, judge_passages
from .corpus import Passage, Skipped, _matches, scan
from .discover import discover
from .memory import Claim, parse_memory
from .ownfiles import DECISION_LOG, GENERATED, REVIEWS, own_files
from .verify import LexicalVerifier, Verifier

MEMORY_NAME = "MEMORY.md"
_SHOWN_FILES = 8  # names in the stderr note; the report lists every one
_OWN_REASONS = {REVIEWS: "review records: a record about memory, not evidence",
                DECISION_LOG: "decision log: a record about memory, not evidence",
                GENERATED: "report generated by Memory Lab: a report cannot be its own evidence"}


def select_memories(directory: Path, exclude: Iterable[str] = ()) -> tuple[list[str], list[Skipped]]:
    """(POSIX paths relative to ``directory`` in path order, what the search passed over).

    Every file ``discover`` lists, once each, plus ``MEMORY.md`` at the top of ``directory``. ``exclude`` globs,
    relative to ``directory``, leave files out."""
    found = discover(directory, exclude=exclude)
    chosen, passed_over = list(found.distinct), list(found.skipped)
    root = Path(directory).resolve()
    # The exact name, even on a case-insensitive filesystem, as discovery does.
    if MEMORY_NAME in os.listdir(root) and not _matches(MEMORY_NAME, found.excluded):
        try:
            resolved = input_path(root, root / MEMORY_NAME)
        except InputPathError as exc:
            passed_over.append(Skipped(path=MEMORY_NAME, reason=f"{exc}"))
        else:
            if not resolved.is_file():
                passed_over.append(Skipped(path=MEMORY_NAME, reason="not a regular file"))
            elif not any((root / name).resolve() == resolved for name in chosen):
                chosen.append(MEMORY_NAME)
    return sorted(chosen), passed_over


def _note(files: list[str], evidence: str, passed_over: list[Skipped]) -> str:
    listed = ", ".join(files[:_SHOWN_FILES])
    if len(files) > _SHOWN_FILES:
        listed += f" and {len(files) - _SHOWN_FILES} more"
    what = f"auditing {listed} against {evidence}" if len(files) == 1 else (
        f"auditing {len(files)} files against {evidence}: {listed}")
    if passed_over:
        what += f" ({len(passed_over)} place(s) not searched: see the report)"
    return "note: " + what


def _in_directory(prefix: PurePosixPath, claim: Claim) -> Claim:
    """A claim whose path and duplicate locations are relative to the audited directory, not its own file's."""
    moved = claim.model_copy(update={"path": (prefix / claim.path).as_posix(),
                                     "also_at": [(prefix / at).as_posix() for at in claim.also_at]})
    moved._raw_copies = [((prefix / stated_at).as_posix(), raw) for stated_at, raw in claim._raw_copies]
    return moved


def _combine(parsed: list[tuple[str, list[Claim]]]) -> tuple[list[Claim], dict[str, str]]:
    """One claim per ID across the files, and which file reports it. A file's own claims go first, so a claim
    counts for a file that states it before it counts for a file that only links to it."""
    combined: dict[str, Claim] = {}
    owner: dict[str, str] = {}
    own = [(name, claim) for name, claims in parsed for claim in claims if claim.path == name]
    linked = [(name, claim) for name, claims in parsed for claim in claims if claim.path != name]
    for name, claim in own + linked:
        kept = combined.get(claim.id)
        if kept is None:
            combined[claim.id] = claim
            owner[claim.id] = name
            continue
        kept._absorb_raw(claim)
        for location in (claim.location, *claim.also_at):
            if location != kept.location and location not in kept.also_at:
                kept.also_at.append(location)
    return list(combined.values()), owner


class _Corpus:
    """The evidence, scanned once, without the files of any one report."""

    def __init__(self, root: Path, passages: list[Passage], skipped: list[Skipped]):
        self.root, self.passages, self.skipped = root, passages, skipped
        self._resolved: dict[str, Path] = {}

    def _file(self, relative: str) -> Path:
        if relative not in self._resolved:
            try:
                self._resolved[relative] = (self.root / relative).resolve()
            except (OSError, RuntimeError):  # a skipped cyclic link: no file of any report
                self._resolved[relative] = self.root / relative
        return self._resolved[relative]

    def without(self, files: list[Path]) -> tuple[list[Passage], list[Skipped]]:
        out = set(files)
        return ([p for p in self.passages if self._file(p.span.path) not in out],
                [s for s in self.skipped if self._file(s.path) not in out])


def audit_directory(directory: Path = Path("."), evidence_root: Path | None = None, reviews: Path | None = None,
                    verifier: Verifier | None = None, as_of: date | None = None, stale_days: int = 180,
                    follow_links: bool = True, max_candidates: int = 3, min_coverage: float = 0.5,
                    max_judged: int | None = None, exclude: Iterable[str] = (), max_concurrency: int = 1,
                    progress: Callable[[str], None] | None = None, check_references: bool = True) -> AuditSet:
    """Audit every memory and instruction file of ``directory`` (see ``select_memories``) against ``evidence_root``,
    by default ``directory`` itself. With no such file, the result has no ``files``. ``progress`` receives one line
    saying which files were chosen. A file that cannot be read raises ``ValueError`` naming it. ``check_references``:
    see ``audit``; the files must sit under ``evidence_root``."""
    directory = Path(directory)
    exclude = [p.strip() for p in exclude if p.strip()]
    evidence = Path(evidence_root) if evidence_root is not None else directory
    verifier = verifier or LexicalVerifier()
    as_of = as_of or date.today()
    names, passed_over = select_memories(directory, exclude)
    if not names:
        return AuditSet(files=[], evidence_root=str(evidence), excluded=exclude, verifier=verifier.name, as_of=as_of,
                        summary={}, reports=[], not_searched=passed_over)
    root = evidence.resolve()
    if not root.is_dir():
        raise EvidenceError(f"evidence root is not a directory: {evidence}")
    if progress is not None:
        progress(_note(names, str(evidence), passed_over))

    parsed: list[tuple[str, list[Claim]]] = []
    read: dict[str, list[Path]] = {}
    memory_skips: dict[str, list[Skipped]] = {}
    for name in names:
        prefix = PurePosixPath(name).parent
        skipped: list[Skipped] = []
        try:
            claims, files = parse_memory(directory / name, follow_links=follow_links, skipped=skipped)
        except (ValueError, OSError) as exc:
            raise ValueError(f"cannot read {name} ({exc}); leave it out with --exclude") from exc
        parsed.append((name, [_in_directory(prefix, claim) for claim in claims]))
        read[name] = files
        memory_skips[name] = [Skipped(path=(prefix / s.path).as_posix(), reason="memory skipped: " + s.reason)
                              for s in skipped]
    claims, owner = _combine(parsed)

    own = own_files(root, exclude)
    if progress is not None and reviews is None:
        for relative, reason in own:
            if reason == REVIEWS and "/" not in relative:  # a review file further down belongs to something else
                progress(f"note: {relative} holds reviews, which apply only with --reviews {relative}")
    left_out = [root / relative for relative, _ in own] + ([Path(reviews)] if reviews else [])
    passages, skipped = scan(root, exclude=exclude, memory_files=left_out) if claims else ([], [])
    # Only when --exclude is what emptied the evidence: a pattern that matches nothing changes nothing.
    if claims and exclude and not passages and scan(root, memory_files=left_out)[0]:
        raise EvidenceError(NOTHING_LEFT)
    corpus = _Corpus(root, passages, skipped)
    own_skips = [Skipped(path=relative, reason=_OWN_REASONS[reason]) for relative, reason in own]
    conflicts = _ConflictIndex(claims) if claims else None
    reports: list[AuditReport] = []
    for name in names:
        targets = [claim for claim in claims if owner[claim.id] == name]
        prefix = PurePosixPath(name).parent
        base = (directory / name).absolute().parent.resolve()
        here, skips = corpus.without(read[name]) if targets else ([], [])
        reports.append(judge_passages(
            claims, targets, here, [*memory_skips[name], *skips, *(own_skips if targets else [])], memory_file=name,
            files_read=[(prefix / p.relative_to(base).as_posix()).as_posix() for p in read[name]],
            evidence_root=evidence, root=root, reviews=reviews, verifier=verifier, as_of=as_of,
            stale_days=stale_days, max_candidates=max_candidates, min_coverage=min_coverage,
            max_judged=max_judged, exclude=exclude, max_concurrency=max_concurrency, conflict_index=conflicts))
    if check_references:
        add_missing_references(reports, claims, directory, root)
    totals = Counter()
    for report in reports:
        totals.update(report.summary)
    return AuditSet(files=names, evidence_root=str(evidence), excluded=exclude, verifier=verifier.name, as_of=as_of,
                    summary={status: totals[status] for status in SEVERITY if totals[status]},
                    reports=reports, not_searched=passed_over)
