"""Memory Lab's own files under an evidence root, recognised by their content.

Review records, decision logs and reports that orgmemory generated are records about memory, not prose a reader
can compare with a claim. ``memfalsify audit`` with no MEMORY argument keeps them out of the evidence, as the web
page does (``memlab_ui.internal``, from which this is copied until memlab-ui can require a memfalsify that has it;
``tests/test_first_run.py`` checks that the two agree). MemFalsify's own reports are not listed here: ``scan``
skips those, with its own reason. Each file is recognised from its first bytes, never by its name alone.
"""
from __future__ import annotations

import json
from collections.abc import Iterable
from pathlib import Path, PurePosixPath

from memcore.paths import SKIP_DIRS, input_path
from memcore.reading import read_file_bytes, read_head, walk_files

from .corpus import _matches, is_report

HEAD = 16 * 1024
REVIEWS = "review records"
DECISION_LOG = "decision log"
GENERATED = "report generated by Memory Lab"

_REVIEW = {"memory_id", "relation", "path", "quote", "reviewer"}
_EVENT = {"id", "timestamp", "actor", "action", "subject", "evidence_ids"}
_ROLE_CHANGE = {"id", "timestamp", "actor", "action", "subject_actor", "role", "evidence_ids"}
_MANIFEST = {"id", "path", "sha256", "quote", "start", "end", "source_uri"}
_CLAIM = {"memory_id", "location", "text"}  # memfalsify claims output
_ORG_REPORTS = ("# Organizational memory replay", "# Organizational decision audit",
                "# Organizational decision changes")
_ORG_HTML = '<meta name="generator" content="orgmemory">'
_ADR = "*Generated by `orgmemory export` from the replayed event log"
_CSV = ("subject,adr_file,status,current_status,decided_at,decision_event,decision_action,decided_by,"
        "decided_by_roles,")
_IMPORTER_SETTINGS = ("github.json", "jira.json")


def classify(name: str, head: bytes, complete: bool, decision_folder: bool) -> str | None:
    """Why a file is one of Memory Lab's own (a reason key), or None for ordinary evidence. ``head`` is its
    first bytes, ``complete`` whether that is all of it, and ``decision_folder`` whether it sits next to a
    decision log's events.jsonl, policy.json and evidence.jsonl."""
    try:
        text = head.decode("utf-8")
    except UnicodeDecodeError as error:
        if complete or error.start < len(head) - 4:  # a cut multi-byte character at the end is fine
            return None
        text = head[:error.start].decode("utf-8")
    text = text.removeprefix("\ufeff")
    if is_report(text):
        return GENERATED
    start = text.lstrip()
    if start.startswith(_ORG_REPORTS) or _ORG_HTML in text[:400] or _ADR in text or text.startswith(_CSV):
        return GENERATED
    first = start.split("\n", 1)[0].strip()
    record = _object(first)
    if record is not None:
        keys = set(record)
        if _REVIEW <= keys:
            return REVIEWS
        if _EVENT <= keys or _ROLE_CHANGE <= keys or _MANIFEST <= keys:
            return DECISION_LOG
        if str(record.get("importer", "")).startswith("orgmemory-"):
            return DECISION_LOG  # an importer's sync state
        if _CLAIM <= keys:
            return GENERATED
    whole = _object(start) if complete else None
    if whole is not None:
        if whole.get("tool") in ("memfalsify", "orgmemory") and whole.get("mode") == "read_only":
            return GENERATED
        if {"actors", "permissions"} <= set(whole):
            return DECISION_LOG
        if decision_folder and name in _IMPORTER_SETTINGS:
            return DECISION_LOG
    return None


def _object(text: str) -> dict | None:
    if not text.startswith("{"):
        return None
    try:
        value = json.loads(text)
    except ValueError:
        return None
    return value if isinstance(value, dict) else None


def own_files(evidence: Path, exclude: Iterable[str] = ()) -> list[tuple[str, str]]:
    """(path relative to ``evidence``, reason key) for each of Memory Lab's own files under it, in walk order.
    The walk skips what the evidence scan skips (hidden, skipped and symlinked folders, hidden files), and files
    the ``exclude`` globs already leave out."""
    patterns = [p.strip().removeprefix("./") for p in exclude if p.strip()]
    found = []

    def skip(error: OSError) -> None:
        return None  # the scan reports what it cannot read

    for current, dirnames, filenames in walk_files(evidence, onerror=skip):
        here = Path(current)
        base = here.relative_to(evidence)
        dirnames[:] = [d for d in sorted(dirnames)
                       if not d.startswith(".") and d not in SKIP_DIRS and not (here / d).is_symlink()
                       and not _matches((base / d).as_posix(), patterns, directory=True)]
        names = set(filenames)
        decision_folder = {"events.jsonl", "policy.json", "evidence.jsonl"} <= names
        for name in sorted(filenames):
            path = here / name
            relative = PurePosixPath(*path.relative_to(evidence).parts).as_posix()
            if name.startswith(".") or not path.is_file() or _matches(relative, patterns):
                continue
            try:
                input_path(evidence, path)  # a link leading out of the root is not read, as in the scan
                head = read_head(path, HEAD + 1)
                complete = len(head) <= HEAD
                if not complete and head.lstrip(b"\xef\xbb\xbf \t\r\n").startswith(b"{"):
                    # A JSON report has its marker inside: read all of it.
                    head, complete = read_file_bytes(path), True
            except (OSError, ValueError):
                continue
            reason = classify(name, head if complete else head[:HEAD], complete, decision_folder)
            if reason is not None and not is_report(head.decode("utf-8", "ignore")):
                found.append((relative, reason))
    return found
